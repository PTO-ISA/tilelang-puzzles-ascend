"""Regenerate the per-variant wall-time table in README.md from a sweep log.

    python -m harness.check > /tmp/sweep.log 2>&1
    python tools/timing_table.py /tmp/sweep.log            # print the table
    python tools/timing_table.py /tmp/sweep.log --write    # update README.md

The table is wall time per variant per tier, measured end to end including
compilation, so it is the number that answers "how long will working this
variant take". It is NOT a performance comparison -- that is simulated VF
cycles, in `tools/vf_cycles.py` and `doc/quant_vf_cycle_comparison.md`. Wall
time here is dominated by compilation and by simulator startup, and a tier being
slower to *compile* says nothing about the kernel it produces.

Generated rather than retyped because there are 88 cells, and a stale timing
table is the kind of thing nobody notices.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
MARKER = "<!-- generated by tools/timing_table.py -->"
TIERS = ("torch", "asc", "pto", "simt")
LABEL = {"torch": "torch", "asc": "ASC", "pto": "PTO", "simt": "SIMT"}
KERNELS = ("cast_back", "per_token", "per_block", "per_channel")

# "  PASS       104.7s  simt/per_token/02_round_sf"
ROW = re.compile(r"^\s*(PASS|FAIL|XFAIL|XPASS|TODO)\s+([\d.]+)s\s+(\S+)\s*$", re.M)


def parse(log: str) -> dict[str, tuple[str, float]]:
    return {m.group(3): (m.group(1), float(m.group(2))) for m in ROW.finditer(log)}


def build(times: dict[str, tuple[str, float]]) -> str:
    names = []
    for kernel in KERNELS:
        for p in sorted((ROOT / "puzzles/asc/quant/answer" / kernel).glob("[0-9]*.py")):
            names.append(f"{kernel}/{p.stem}")

    out = [MARKER, "",
           "| variant | " + " | ".join(LABEL[t] for t in TIERS) + " |",
           "|---|" + "---|" * len(TIERS)]
    worst = {t: (0.0, "") for t in TIERS}
    totals = {t: 0.0 for t in TIERS}
    missing = []
    for name in names:
        cells = []
        for t in TIERS:
            hit = times.get(f"{t}/{name}")
            if hit is None:
                cells.append("—")
                missing.append(f"{t}/{name}")
                continue
            verdict, secs = hit
            totals[t] += secs
            if secs > worst[t][0]:
                worst[t] = (secs, name)
            cell = f"{secs:.1f} s" if verdict == "PASS" else f"{secs:.1f} s ({verdict})"
            # bold anything over the 60 s per-variant target
            cells.append(f"**{cell}**" if secs > 60 else cell)
        out.append(f"| `{name}` | " + " | ".join(cells) + " |")

    out.append("| **whole tier** | " + " | ".join(
        f"**{totals[t] / 60:.1f} min**" for t in TIERS) + " |")
    out += ["", MARKER]
    if missing:
        print(f"warning: {len(missing)} variant(s) absent from the log, "
              f"e.g. {missing[0]}", file=sys.stderr)
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("log", help="output of a full `python -m harness.check` sweep")
    ap.add_argument("--write", action="store_true", help="update README.md in place")
    args = ap.parse_args()

    times = parse(Path(args.log).read_text(errors="replace"))
    if not times:
        print("no result rows found in that log", file=sys.stderr)
        return 2
    table = build(times)
    if not args.write:
        print(table)
        return 0

    s = README.read_text()
    parts = s.split(MARKER)
    if len(parts) != 3:
        print(f"README.md: expected exactly two {MARKER} lines, "
              f"found {len(parts) - 1}", file=sys.stderr)
        return 2
    README.write_text(parts[0] + table + parts[2])
    print(f"rewrote the timing table in README.md ({len(times)} rows parsed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
