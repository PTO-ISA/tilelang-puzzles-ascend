"""Regenerate the measurement table in doc/ladder-audit.md.

    python tools/ladder_table.py             # print the markdown table
    python tools/ladder_table.py --check     # fail if doc/ladder-audit.md is stale

Three numbers per variant and tier, all taken from the ``BEGIN/END SOLUTION``
region -- which is exactly what the student writes, and nothing else:

* **lines** -- substantive lines: non-blank, non-comment.
* **delta** -- lines changed against the *preceding* variant in the same kernel
  and tier, counted as insertions plus deletions over a ``SequenceMatcher``
  alignment of the two regions. A variant that reverts to an earlier body scores
  a large delta against its immediate predecessor and a small one against the
  variant it actually resembles; where that happens the page says so in prose.
* **new intrinsics** -- names used in this variant's region that no earlier
  variant in the same kernel used. For the SIMD tiers that is ``S.*`` / ``V.*``;
  for SIMT it is the ``T.*`` builtins, since SIMT has no vector intrinsics and
  its arithmetic is plain operators. The two columns are therefore *not*
  comparable to each other -- each says "does this variant introduce a primitive
  the kernel has not needed before" within its own tier.

This was hand-maintained prose until the SIMT tier arrived and needed a fourth
column; it is generated now so the published numbers cannot drift from the files.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / "doc" / "ladder-audit.md"
KERNELS = ("cast_back", "per_token", "per_block", "per_channel")
TIERS = ("torch", "asc", "pto", "simt")

# What counts as "an intrinsic" per tier.
INTRIN = {
    "asc": re.compile(r"\bS\.(\w+)"),
    "pto": re.compile(r"\bV\.(\w+)"),
    "simt": re.compile(r"\bT\.(\w+)"),
}
MARKER = "<!-- generated by tools/ladder_table.py -->"


def region(path: Path) -> list[str] | None:
    """Substantive source lines inside the SOLUTION region, stripped."""
    if not path.exists():
        return None
    out, inside = [], False
    for ln in path.read_text().splitlines():
        st = ln.strip()
        if "BEGIN SOLUTION" in st:
            inside = True
            continue
        if "END SOLUTION" in st:
            inside = False
            continue
        if inside and st and not st.startswith("#"):
            out.append(st)
    return out


def delta(a: list[str] | None, b: list[str] | None) -> int | None:
    if a is None or b is None:
        return None
    adds = dels = 0
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b).get_opcodes():
        if tag in ("replace", "delete"):
            dels += i2 - i1
        if tag in ("replace", "insert"):
            adds += j2 - j1
    return adds + dels


def build() -> str:
    rows = []
    for kernel in KERNELS:
        names = [p.name for p in
                 sorted((ROOT / "puzzles/asc/quant/answer" / kernel).glob("[0-9]*.py"))]
        seen = {t: set() for t in INTRIN}
        prev: dict[str, list[str] | None] = {t: None for t in TIERS}
        for i, name in enumerate(names):
            reg = {t: region(ROOT / "puzzles" / t / "quant/answer" / kernel / name)
                   for t in TIERS}
            d = {t: (delta(prev[t], reg[t]) if i else None) for t in TIERS}
            new = {}
            for t, pat in INTRIN.items():
                if reg[t] is None:
                    new[t] = None
                    continue
                used = {m for ln in reg[t] for m in pat.findall(ln)}
                new[t] = len(used - seen[t])
                seen[t] |= used
            rows.append((f"{kernel}/{name[:-3]}", reg, d, new))
            prev = reg
    n = lambda v: "—" if v is None else str(v)

    def bold(v, hi, lo=None):
        """Bold the extremes: a long region/delta, or a suspiciously short one."""
        if v is None:
            return "—"
        if v >= hi or (lo is not None and v <= lo):
            return f"**{v}**"
        return str(v)
    out = [
        MARKER,
        "",
        "| variant | torch | ASC | PTO | SIMT | Δ ASC | Δ PTO | Δ SIMT "
        "| new ASC | new SIMT |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, reg, d, new in rows:
        ln = {t: (len(reg[t]) if reg[t] is not None else None) for t in TIERS}
        out.append(
            f"| {name} | {n(ln['torch'])} | {bold(ln['asc'], 45, 4)} | "
            f"{bold(ln['pto'], 45, 4)} | {bold(ln['simt'], 45, 4)} | "
            f"{bold(d['asc'], 60)} | {bold(d['pto'], 60)} | {bold(d['simt'], 60)} | "
            f"{'**0**' if new['asc'] == 0 else n(new['asc'])} | "
            f"{'**0**' if new['simt'] == 0 else n(new['simt'])} |")
    tot = {t: sum(len(r[1][t]) for r in rows if r[1][t] is not None) for t in TIERS}
    out += [
        f"| **total** | **{tot['torch']}** | **{tot['asc']}** | **{tot['pto']}** "
        f"| **{tot['simt']}** | | | | | |",
        "",
        "Bold marks an extreme worth looking at: a region of 45+ lines or of 4 "
        "or fewer, a delta of 60+, or a variant that introduces **no** new "
        "intrinsic in that tier. A very short region is a *weak exercise* flag -- "
        "the student writes almost nothing while the real change sits outside the "
        "sentinels.",
        MARKER,
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the audit page is out of date")
    ap.add_argument("--write", action="store_true",
                    help="replace the table in doc/ladder-audit.md in place")
    args = ap.parse_args()
    table = build()

    if not (args.check or args.write):
        print(table)
        return 0

    s = AUDIT.read_text()
    parts = s.split(MARKER)
    if len(parts) != 3:
        print(f"{AUDIT.relative_to(ROOT)}: expected exactly two {MARKER} lines, "
              f"found {len(parts) - 1}")
        return 2
    fresh = parts[0] + table + parts[2]
    if args.check:
        if fresh != s:
            print(f"{AUDIT.relative_to(ROOT)} is stale -- "
                  f"run: python tools/ladder_table.py --write")
            return 1
        print(f"{AUDIT.relative_to(ROOT)}: table up to date")
        return 0
    AUDIT.write_text(fresh)
    print(f"rewrote the table in {AUDIT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
